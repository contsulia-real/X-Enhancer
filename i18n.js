function xeLocale(lang = document.documentElement.lang) {
  const value = String(lang || "").toLowerCase().replace(/_/g, "-");
  if (value.startsWith("zh")) {
    const parts = value.split("-");
    return parts.includes("hant") || (!parts.includes("hans") && parts.some(part => ["tw", "hk", "mo"].includes(part)))
      ? "zh-Hant" : "zh-CN";
  }
  if (/^ja(?:-|$)/.test(value)) return "ja";
  if (/^ko(?:-|$)/.test(value)) return "ko";
  if (/^fr(?:-|$)/.test(value)) return "fr";
  return "en";
}
function xeText(key, lang = xeLocale()) { return XE_TEXT[lang]?.[key] ?? key; }
